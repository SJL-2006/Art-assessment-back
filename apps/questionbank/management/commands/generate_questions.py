def _opts(a, b, c, d):
    return [
        {"key": "A", "text": a},
        {"key": "B", "text": b},
        {"key": "C", "text": c},
        {"key": "D", "text": d},
    ]


def single(stem, a, b, c, d, answer, analysis, difficulty="medium", score=2):
    return {
        "qtype": "single",
        "stem": stem,
        "options": _opts(a, b, c, d),
        "answer": answer,
        "analysis": analysis,
        "difficulty": difficulty,
        "score": score,
    }


def judge(stem, correct, analysis, difficulty="easy", score=1):
    return {
        "qtype": "judge",
        "stem": stem,
        "options": [],
        "answer": "正确" if correct else "错误",
        "analysis": analysis,
        "difficulty": difficulty,
        "score": score,
    }


