class Command(BaseCommand):
    help = "批量生成音乐 / 美术题库（仅单选、判断题，幂等）。"

    @transaction.atomic
    def handle(self, *args, **options):
        admin = User.objects.filter(is_superuser=True).first() or User.objects.filter(
            role=User.ROLE_QB_ADMIN,
        ).first()
        if admin is None:
            admin = User.objects.create_user(
                username="admin",
                password="admin123456",
                role=User.ROLE_QB_ADMIN,
                real_name="题库管理员",
                is_staff=True,
                is_superuser=True,
            )

        music, _ = Course.objects.get_or_create(name="音乐", defaults={"code": "music"})
        art, _ = Course.objects.get_or_create(name="美术", defaults={"code": "art"})

        total = 0
        for course, by_chapter in ((music, MUSIC_BY_CHAPTER), (art, ART_BY_CHAPTER)):
            grade_idx = 0
            for chapter_name, questions in by_chapter.items():
                chapter, _ = Chapter.objects.get_or_create(
                    course=course, name=chapter_name, defaults={"sort": grade_idx + 1},
                )
                for q in questions:
                    grade = GRADES[grade_idx % len(GRADES)]
                    grade_idx += 1
                    _, is_new = Question.objects.get_or_create(
                        course=course,
                        chapter=chapter,
                        qtype=q["qtype"],
                        stem=q["stem"],
                        defaults={
                            "difficulty": q["difficulty"],
                            "grade": grade,
                            "options": q["options"],
                            "answer": q["answer"],
                            "analysis": q["analysis"],
                            "score": q["score"],
                            "status": Question.STATUS_APPROVED,
                            "creator": admin,
                            "reviewer": admin,
                        },
                    )
                    total += int(is_new)

        # 补充题：按年级补齐困难单选 / 判断中高难度
        for course, supplement in ((music, MUSIC_SUPPLEMENT_BY_GRADE), (art, ART_SUPPLEMENT_BY_GRADE)):
            supp_chapter, _ = Chapter.objects.get_or_create(
                course=course, name="进阶提升", defaults={"sort": 99},
            )
            for grade, questions in supplement.items():
                for q in questions:
                    _, is_new = Question.objects.get_or_create(
                        course=course,
                        chapter=supp_chapter,
                        qtype=q["qtype"],
                        stem=q["stem"],
                        defaults={
                            "difficulty": q["difficulty"],
                            "grade": grade,
                            "options": q["options"],
                            "answer": q["answer"],
                            "analysis": q["analysis"],
                            "score": q["score"],
                            "status": Question.STATUS_APPROVED,
                            "creator": admin,
                            "reviewer": admin,
                        },
                    )
                    total += int(is_new)

        music_total = sum(len(v) for v in MUSIC_BY_CHAPTER.values()) + sum(
            len(v) for v in MUSIC_SUPPLEMENT_BY_GRADE.values()
        )
        art_total = sum(len(v) for v in ART_BY_CHAPTER.values()) + sum(
            len(v) for v in ART_SUPPLEMENT_BY_GRADE.values()
        )
        self.stdout.write(self.style.SUCCESS(f"题库生成完成，新增 {total} 道题。"))
        self.stdout.write(f"  音乐：{music_total} 道")
        self.stdout.write(f"  美术：{art_total} 道")
        self.stdout.write("  状态均为「已通过」，随机组卷可直接抽到。")
